% ==========================================
% 2. KELAS LAPTOP
% ==========================================
% ENTRY (Di bawah 10 Juta)
kelas_laptop(ID, entry) :- spesifikasi(ID, _, _, _, _, _, _, Harga), Harga < 10.

% MIDRANGE (10 - 19 Juta)
kelas_laptop(ID, midrange) :- spesifikasi(ID, _, _, _, _, _, _, Harga), Harga >= 10, Harga < 20.

% HIGH-END (20 - 34 Juta)
kelas_laptop(ID, high_end) :- spesifikasi(ID, _, _, _, _, _, _, Harga), Harga >= 20, Harga < 35.

% FLAGSHIP (35 Juta ke atas)
kelas_laptop(ID, flagship) :- spesifikasi(ID, _, _, _, _, _, _, Harga), Harga >= 35.


% ==========================================
% 3. KEBUTUHAN (PENGGUNAAN)
% Rule berbasis AI/Logika Otomatis dari Spesifikasi
% ==========================================

% 1. OFFICE (Semua laptop bisa office)
cocok_untuk(ID, office) :- 
    spesifikasi(ID, _, _, _, _, _, _, _).

% 2. KODING (RAM minimal 8GB, direkomendasikan 16GB)
cocok_untuk(ID, koding) :- 
    spesifikasi(ID, _, _, _, RAM, _, _, _),
    RAM >= 8.

% 3. EDITING RINGAN (Figma, Photoshop, Video 1080p -> RAM min 8GB, CPU lumayan)
cocok_untuk(ID, editing_ringan) :- 
    spesifikasi(ID, _, _, _, RAM, _, _, Harga),
    RAM >= 8, Harga >= 7.

% 4. EDITING BERAT (Video 4K, 3D Rendering, After Effects -> RAM min 16GB, butuh GPU dedicated atau chip Apple M)
cocok_untuk(ID, editing_berat) :- 
    spesifikasi(ID, _, _, _, RAM, _, VGA, _),
    RAM >= 16,
    (sub_atom(VGA, _, _, _, 'RTX') ; sub_atom(VGA, _, _, _, 'Apple') ; sub_atom(VGA, _, _, _, 'RX')).

% 5. GAMING (Butuh GPU dedicated seperti RTX, GTX, RX, bukan sekadar Intel UHD/Iris)
cocok_untuk(ID, gaming) :- 
    spesifikasi(ID, _, _, _, _, _, VGA, _),
    (sub_atom(VGA, _, _, _, 'RTX') ; sub_atom(VGA, _, _, _, 'GTX') ; sub_atom(VGA, _, _, _, 'RX')).

% 6. STREAMING (Bermain game sambil streaming -> RAM min 16GB, GPU dedicated RTX/RX)
cocok_untuk(ID, streaming) :- 
    spesifikasi(ID, _, _, _, RAM, _, VGA, _),
    RAM >= 16,
    (sub_atom(VGA, _, _, _, 'RTX') ; sub_atom(VGA, _, _, _, 'RX')).


% ==========================================
% 4. RULES PENCARIAN
% ==========================================

rekomendasi_ideal(Kebutuhan, Kelas, Merk, Model, RAM, VGA, Harga) :-
    cocok_untuk(ID, Kebutuhan),
    kelas_laptop(ID, Kelas),
    spesifikasi(ID, Merk, Model, _, RAM, _, VGA, Harga).

rekomendasi_kompleks(Kebutuhan1, Kebutuhan2, Kelas, Merk, Model, Harga) :-
    cocok_untuk(ID, Kebutuhan1),
    cocok_untuk(ID, Kebutuhan2),
    kelas_laptop(ID, Kelas),
    spesifikasi(ID, Merk, Model, _, _, _, _, Harga).